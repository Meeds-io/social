package io.meeds.social.oauthClient.controller;

import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.security.oauth2.core.oidc.user.OidcUser;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.Map;

@RestController
public class ClientController {

  @GetMapping("/")
  public String home() {
    return "Welcome to OAuth2 Client!";
  }

  @GetMapping("/me")
  public Map<String, Object> me(@AuthenticationPrincipal
  OidcUser oidcUser) {
    return Map.of("name", oidcUser.getFullName(), "email", oidcUser.getEmail(), "claims", oidcUser.getClaims());
  }
}
